# ============================================
# 1. CONCEPT
# ============================================
# Variables are names bound to values. Python is dynamically typed, so a variable's type is determined by the value assigned to it.

# ============================================
# 2. EXAMPLE
# ============================================

student_name = "Aulia"
student_age = 21
is_active = True
print(student_name, student_age, is_active)

