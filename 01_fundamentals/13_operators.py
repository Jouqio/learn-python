# ============================================
# 2. EXAMPLE
# ============================================

a, b = 10, 3
print(a + b, a - b, a * b, a / b, a // b, a % b, a ** b)
print(a > b, a == b, a != b)
print(5 in [1, 5, 9], 5 not in [1, 2, 3])

